#!/usr/bin/env python3
"""Freeze a trajectory genome into a standalone Kaggriculture main.py."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from pprint import pformat

from trajectory_genome import TrajectoryGenome


MARKER = "# --- BEGIN FROZEN SPATIAL TRAJECTORY ---"
RUNTIME_START = "# --- BEGIN TRAJECTORY RUNTIME ---"
RUNTIME_END = "# --- END TRAJECTORY RUNTIME ---"


def runtime_source() -> str:
    source = Path(__file__).with_name("trajectory_genome.py").read_text(
        encoding="utf-8"
    )
    start = source.index(RUNTIME_START) + len(RUNTIME_START)
    end = source.index(RUNTIME_END)
    return source[start:end].strip()


def build(base: Path, trajectory_path: Path) -> str:
    source = base.read_text(encoding="utf-8")
    if MARKER in source:
        source = source.split(MARKER, 1)[0].rstrip() + "\n"
    trajectory = TrajectoryGenome(
        **json.loads(trajectory_path.read_text(encoding="utf-8"))
    ).normalized()
    block = f'''\
{MARKER}
# Generated by training/promote_trajectory.py from {trajectory_path.name}.
# Runtime compiler and trajectory values are embedded; no local imports required.
# Keep the compiler in an isolated module because promoted incumbents may
# already contain schedule/genome helpers with names such as ``phase_index``.
import sys as _trajectory_sys
import types as _trajectory_types

_trajectory_runtime = _trajectory_types.ModuleType("_frozen_trajectory_runtime")
_trajectory_sys.modules[_trajectory_runtime.__name__] = _trajectory_runtime
exec({runtime_source()!r}, _trajectory_runtime.__dict__)
_TrajectoryGenome = _trajectory_runtime.TrajectoryGenome

_FROZEN_TRAJECTORY = {pformat(trajectory.to_dict(), sort_dicts=False, width=88)}


class _TrajectoryModuleProxy:
    def __getattr__(self, name):
        try:
            return globals()[name]
        except KeyError as error:
            raise AttributeError(name) from error

    def __setattr__(self, name, value):
        globals()[name] = value


_configured_trajectory_agent = _trajectory_runtime.configure_module(
    _TrajectoryModuleProxy(), _TrajectoryGenome(**_FROZEN_TRAJECTORY)
)

# ``main.py`` already contains a ``kaggle_agent`` key.  Deleting it before
# redefining it moves the final callable to the end of the execution namespace,
# which is the selection rule used by Kaggle's raw-file loader.
try:
    del kaggle_agent
except NameError:
    pass


def kaggle_agent(obs, config=None):
    return _configured_trajectory_agent(obs, config)


agent = kaggle_agent
# --- END FROZEN SPATIAL TRAJECTORY ---
'''
    candidate = source.rstrip() + "\n\n\n" + block
    compile(candidate, str(base), "exec")
    return candidate


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--trajectory", type=Path, required=True)
    parser.add_argument("--base", type=Path, required=True)
    parser.add_argument("--output", type=Path, default=Path("candidate_main.py"))
    args = parser.parse_args()
    candidate = build(args.base.resolve(), args.trajectory.resolve())
    args.output.write_text(candidate, encoding="utf-8")
    print(f"wrote standalone trajectory candidate: {args.output}")


if __name__ == "__main__":
    main()
