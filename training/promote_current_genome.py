#!/usr/bin/env python3
"""Freeze a CurrentGenome overlay into a standalone Kaggriculture main.py."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from pprint import pformat

from current_genome import CurrentGenome


MARKER = "# --- BEGIN FROZEN CURRENT GENOME ---"


def runtime_source() -> str:
    source = Path(__file__).with_name("current_genome.py").read_text(encoding="utf-8")
    start = source.index("# --- BEGIN CURRENT GENOME RUNTIME ---")
    end = source.index("# --- END CURRENT GENOME RUNTIME ---")
    return source[start:end]


def build(base: Path, genome_values: dict, source_name: str) -> str:
    source = base.read_text(encoding="utf-8")
    if MARKER in source:
        source = source.split(MARKER, 1)[0].rstrip() + "\n"
    genome = CurrentGenome(**genome_values).normalized()
    block = f'''\
{MARKER}
# Generated by training/promote_current_genome.py from {source_name}.
import sys as _current_genome_sys
import types as _current_genome_types

_current_genome_runtime = _current_genome_types.ModuleType("_frozen_current_genome_runtime")
_current_genome_sys.modules[_current_genome_runtime.__name__] = _current_genome_runtime
exec({runtime_source()!r}, _current_genome_runtime.__dict__)
_CurrentGenome = _current_genome_runtime.CurrentGenome
_FROZEN_CURRENT_GENOME = {pformat(genome.to_dict(), sort_dicts=False, width=88)}


class _CurrentGenomeModuleProxy:
    def __getattr__(self, name):
        try:
            return globals()[name]
        except KeyError as error:
            raise AttributeError(name) from error

    def __setattr__(self, name, value):
        globals()[name] = value


_configured_current_genome_agent = _current_genome_runtime.configure_module(
    _CurrentGenomeModuleProxy(), _CurrentGenome(**_FROZEN_CURRENT_GENOME)
)

try:
    del kaggle_agent
except NameError:
    pass


def kaggle_agent(obs, config=None):
    return _configured_current_genome_agent(obs, config)


agent = kaggle_agent
# --- END FROZEN CURRENT GENOME ---
'''
    candidate = source.rstrip() + "\n\n\n" + block
    compile(candidate, str(base), "exec")
    return candidate


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    source = parser.add_mutually_exclusive_group(required=True)
    source.add_argument("--genome", type=Path)
    source.add_argument("--result", type=Path,
                        help="stage/final JSON; select one entry from its results list")
    parser.add_argument("--result-index", type=int, default=0)
    parser.add_argument("--base", type=Path, required=True)
    parser.add_argument("--output", type=Path, default=Path("candidate_main.py"))
    args = parser.parse_args()
    if args.genome is not None:
        genome_values = json.loads(args.genome.read_text(encoding="utf-8"))
        source_name = args.genome.name
    else:
        result = json.loads(args.result.read_text(encoding="utf-8"))
        genome_values = result["results"][args.result_index]["genome"]
        source_name = f"{args.result.name}:results[{args.result_index}]"
    candidate = build(args.base.resolve(), genome_values, source_name)
    args.output.write_text(candidate, encoding="utf-8")
    print(f"wrote standalone current-genome candidate: {args.output}")


if __name__ == "__main__":
    main()
