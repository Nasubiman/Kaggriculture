#!/usr/bin/env python3
"""Freeze a strategy genome into a standalone Kaggriculture agent file."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from pprint import pformat

from strategy_genome import StrategyGenome, layout_targets


MARKER = "# --- BEGIN FROZEN STRATEGY GENOME ---"


def frozen_block(genome: StrategyGenome, genome_path: Path) -> str:
    genome = genome.normalized()
    middle = layout_targets(genome, phase="middle")
    late = layout_targets(genome, phase="late")
    values = genome.to_dict()
    source_name = genome_path.name
    return f'''\
{MARKER}
# Generated by training/promote_strategy_genome.py from {source_name}.
# This block is self-contained; the submitted agent does not read the JSON file.
_FROZEN_GENOME = {pformat(values, sort_dicts=False, width=88)}
_FROZEN_MIDDLE_TARGETS = {pformat(middle, sort_dicts=False, width=88)}
_FROZEN_LATE_TARGETS = {pformat(late, sort_dicts=False, width=88)}

COW_START_DAY = _FROZEN_GENOME["transition_day"]
COW_TARGET = _FROZEN_GENOME["cow_count"]
SHEEP_TARGET = _FROZEN_GENOME["sheep_count"]
WHEAT_TILES = _FROZEN_GENOME["wheat_tiles"]
CASH_CROP_TILES = _FROZEN_GENOME["cash_tiles"]
COW_HANDS = _FROZEN_GENOME["mature_hands"]
COW_PURCHASE_BATCH = _FROZEN_GENOME["purchase_batch"]
COW_FIRST_PURCHASE = _FROZEN_GENOME["cow_first"]
WHEAT_PICKUP_BATCH = _FROZEN_GENOME["wheat_pickup_batch"]
SALE_PROCEEDS_FACTOR = _FROZEN_GENOME["sale_factor"]
OPENING_ANIMAL = _FROZEN_GENOME["opening_animal"]
OPENING_ANIMAL_TARGET = _FROZEN_GENOME["opening_animals"]
OPENING_REPLANT = _FROZEN_GENOME["replant"]
USE_LEARNED_MACRO = False
crop_agent.TARGET_HANDS = _FROZEN_GENOME["opening_hands"]

_frozen_phase_state = {{"late": False}}
_cow_targets = lambda _size: (
    _FROZEN_LATE_TARGETS["cows"]
    if _frozen_phase_state["late"]
    else _FROZEN_MIDDLE_TARGETS["cows"]
)
_sheep_targets = lambda _size: (
    _FROZEN_LATE_TARGETS["sheep"]
    if _frozen_phase_state["late"]
    else _FROZEN_MIDDLE_TARGETS["sheep"]
)
_wheat_targets = lambda _size: (
    _FROZEN_LATE_TARGETS["wheat"]
    if _frozen_phase_state["late"]
    else _FROZEN_MIDDLE_TARGETS["wheat"]
)
_cash_crop_targets = lambda _size: (
    _FROZEN_LATE_TARGETS["cash"]
    if _frozen_phase_state["late"]
    else _FROZEN_MIDDLE_TARGETS["cash"]
)


def _apply_frozen_phase(day):
    global COW_TARGET, SHEEP_TARGET, WHEAT_TILES, CASH_CROP_TILES, COW_HANDS
    global CARE_PRIORITY, FERTILIZER_PRIORITY, ANIMAL_HARVEST_PRIORITY
    late = day >= _FROZEN_GENOME["second_transition_day"]
    _frozen_phase_state["late"] = late
    if late:
        COW_TARGET = _FROZEN_GENOME["late_cow_count"]
        SHEEP_TARGET = _FROZEN_GENOME["late_sheep_count"]
        WHEAT_TILES = _FROZEN_GENOME["late_wheat_tiles"]
        CASH_CROP_TILES = _FROZEN_GENOME["late_cash_tiles"]
        COW_HANDS = _FROZEN_GENOME["late_hands"]
        order = _FROZEN_GENOME["late_service_order"].split("_")
    else:
        COW_TARGET = _FROZEN_GENOME["cow_count"]
        SHEEP_TARGET = _FROZEN_GENOME["sheep_count"]
        WHEAT_TILES = _FROZEN_GENOME["wheat_tiles"]
        CASH_CROP_TILES = _FROZEN_GENOME["cash_tiles"]
        COW_HANDS = _FROZEN_GENOME["mature_hands"]
        order = _FROZEN_GENOME["service_order"].split("_")
    priorities = {{name: index + 3 for index, name in enumerate(order)}}
    CARE_PRIORITY = priorities["care"]
    FERTILIZER_PRIORITY = priorities["fertilizer"]
    ANIMAL_HARVEST_PRIORITY = priorities["harvest"]


_opening_plan_before_frozen_genome = _opening_plan
if _FROZEN_GENOME["opening_mode"] == "generic":
    def _opening_plan(board_size):
        plan = crop_agent._plan(board_size, False)
        for position in _opening_animal_targets(board_size):
            plan.pop(position, None)
        return plan


_agent_before_frozen_genome = agent


def agent(obs):
    day = int(obs.get("day", 0))
    _apply_frozen_phase(day)
    if _FROZEN_GENOME["opening_mode"] == "rui_scripted" or day > 0:
        return _agent_before_frozen_genome(obs)
    farms = obs.get("farms", []) or []
    player = int(obs.get("player", 0))
    if player >= len(farms):
        return {{"farmer": ["PASS"], "hands": [], "market": []}}
    farm = farms[player]
    private = obs.get("private", {{}}) or {{}}
    actions = _opening_actions(obs, farm, private)
    return {{
        "farmer": actions[0] if actions else ["PASS"],
        "hands": actions[1:],
        "market": _opening_market_actions(obs, farm, private),
    }}
# --- END FROZEN STRATEGY GENOME ---
'''


def build(base: Path, genome_path: Path) -> str:
    source = base.read_text(encoding="utf-8")
    if MARKER in source:
        # Re-promoting a later run must replace, not stack, the old wrapper.
        source = source.split(MARKER, 1)[0].rstrip() + "\n"
    genome = StrategyGenome(
        **json.loads(genome_path.read_text(encoding="utf-8"))
    ).normalized()
    candidate = source.rstrip() + "\n\n\n" + frozen_block(genome, genome_path)
    compile(candidate, str(base), "exec")
    return candidate


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--genome", type=Path, required=True)
    parser.add_argument("--base", type=Path, required=True)
    parser.add_argument("--output", type=Path, default=Path("candidate_main.py"))
    args = parser.parse_args()

    candidate = build(args.base.resolve(), args.genome.resolve())
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(candidate, encoding="utf-8")
    print(f"wrote standalone candidate: {args.output}")


if __name__ == "__main__":
    main()
