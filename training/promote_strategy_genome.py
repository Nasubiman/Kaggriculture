#!/usr/bin/env python3
"""Freeze a strategy genome into a standalone Kaggriculture agent file."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from pprint import pformat

from strategy_genome import StrategyGenome


MARKER = "# --- BEGIN FROZEN STRATEGY GENOME ---"
RUNTIME_START = "LAYOUT_FAMILIES ="
RUNTIME_END = "FIELD_CHOICES:"


def runtime_source() -> str:
    """Return the exact inference-only genome compiler used during search."""
    path = Path(__file__).with_name("strategy_genome.py")
    source = path.read_text(encoding="utf-8")
    start = source.index(RUNTIME_START)
    end = source.index(RUNTIME_END)
    return source[start:end].rstrip()


def frozen_block(genome: StrategyGenome, genome_path: Path) -> str:
    values = genome.normalized().to_dict()
    compiler = runtime_source()
    return f'''\
{MARKER}
# Generated by training/promote_strategy_genome.py from {genome_path.name}.
# The compiler and values are embedded; no project files are imported at runtime.
from dataclasses import asdict, dataclass, replace
from typing import Any

{compiler}

_FROZEN_GENOME = {pformat(values, sort_dicts=False, width=88)}
_opening_plan_before_frozen_genome = _opening_plan
_agent_before_frozen_genome = agent


class _FrozenModuleProxy:
    def __getattr__(self, name):
        return globals()[name]

    def __setattr__(self, name, value):
        globals()[name] = value


_configured_agent = configure_module(
    _FrozenModuleProxy(), StrategyGenome(**_FROZEN_GENOME)
)


def kaggle_agent(obs):
    """Final callable: Kaggle selects the last callable defined in this file."""
    return _configured_agent(obs)


agent = kaggle_agent
# --- END FROZEN STRATEGY GENOME ---
'''


def build(base: Path, genome_path: Path) -> str:
    source = base.read_text(encoding="utf-8")
    if MARKER in source:
        # Re-promoting a later run replaces rather than stacks the old wrapper.
        source = source.split(MARKER, 1)[0].rstrip() + "\n"
    genome = StrategyGenome(
        **json.loads(genome_path.read_text(encoding="utf-8"))
    ).normalized()
    candidate = source.rstrip() + "\n\n\n" + frozen_block(genome, genome_path)
    compile(candidate, str(base), "exec")
    return candidate


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--genome", type=Path, required=True)
    parser.add_argument("--base", type=Path, required=True)
    parser.add_argument("--output", type=Path, default=Path("candidate_main.py"))
    args = parser.parse_args()

    candidate = build(args.base.resolve(), args.genome.resolve())
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(candidate, encoding="utf-8")
    print(f"wrote standalone candidate: {args.output}")


if __name__ == "__main__":
    main()
