#!/usr/bin/env python3
"""Freeze a daily schedule genome into a standalone Kaggriculture main.py."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from pprint import pformat

from schedule_genome import ScheduleGenome


MARKER = "# --- BEGIN FROZEN DAILY SCHEDULE ---"
RUNTIME_START = "# --- BEGIN SCHEDULE RUNTIME ---"
RUNTIME_END = "# --- END SCHEDULE RUNTIME ---"


def runtime_source() -> str:
    source = Path(__file__).with_name("schedule_genome.py").read_text(
        encoding="utf-8"
    )
    start = source.index(RUNTIME_START) + len(RUNTIME_START)
    end = source.index(RUNTIME_END)
    return source[start:end].strip()


def build(base: Path, schedule_path: Path) -> str:
    source = base.read_text(encoding="utf-8")
    if MARKER in source:
        source = source.split(MARKER, 1)[0].rstrip() + "\n"
    schedule = ScheduleGenome(
        **json.loads(schedule_path.read_text(encoding="utf-8"))
    ).normalized()
    block = f'''\
{MARKER}
# Generated by training/promote_schedule.py from {schedule_path.name}.
# Runtime compiler and schedule values are embedded; no local imports required.
{runtime_source()}

_FROZEN_SCHEDULE = {pformat(schedule.to_dict(), sort_dicts=False, width=88)}


class _ScheduleModuleProxy:
    def __getattr__(self, name):
        try:
            return globals()[name]
        except KeyError as error:
            raise AttributeError(name) from error

    def __setattr__(self, name, value):
        globals()[name] = value


_configured_schedule_agent = configure_module(
    _ScheduleModuleProxy(), ScheduleGenome(**_FROZEN_SCHEDULE)
)


def schedule_kaggle_agent(obs, config=None):
    return _configured_schedule_agent(obs, config)


agent = schedule_kaggle_agent
# --- END FROZEN DAILY SCHEDULE ---
'''
    candidate = source.rstrip() + "\n\n\n" + block
    compile(candidate, str(base), "exec")
    return candidate


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--schedule", type=Path, required=True)
    parser.add_argument("--base", type=Path, required=True)
    parser.add_argument("--output", type=Path, default=Path("candidate_main.py"))
    args = parser.parse_args()
    candidate = build(args.base.resolve(), args.schedule.resolve())
    args.output.write_text(candidate, encoding="utf-8")
    print(f"wrote standalone schedule candidate: {args.output}")


if __name__ == "__main__":
    main()
