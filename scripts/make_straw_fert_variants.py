#!/usr/bin/env python3
"""Append a strawberry-fertilize wrapper to a base agent.

A strawberry produces every 2 days; watering on the day before a production day
only keeps the plant alive (one unwatered day is harmless), while fertilizer
applied that day still covers the next day's production (fertilizer lasts the
day it is applied plus two). A worker that carries spare fertilizer and is
about to water a strawberry that was watered yesterday, produces tomorrow and is
not yet fertilized for tomorrow fertilizes it instead; the tape waters it again
tomorrow. Spec: NAME=FIRST_DAY:LAST_STEP:CROPS(+-joined)
"""
from __future__ import annotations

import argparse
from pathlib import Path

WRAPPER = '''

# ---- strawberry fertilize (generated by scripts/make_straw_fert_variants.py): on the day before a
# production day, a worker carrying spare fertilizer fertilizes instead of watering ----
_SF_FIRST_DAY = {first_day}
_SF_LAST_STEP = {last_step}
_SF_CROPS = {crops!r}
_SF_REPORT = {{"sf_applied": 0, "sf_errors": 0}}
_SF_BASE = [_v for _v in list(globals().values()) if callable(_v)][-1]
_SF_INFO = {{"STRAWBERRY": (10, 2, 4), "TOMATO": (8, 1, 4)}}


def straw_fert_agent(observation, configuration=None):
    action = _SF_BASE(observation, configuration)
    try:
        step = int(_get(observation, "step", 0) or 0)
        day = step // 24
        if day < _SF_FIRST_DAY or step > _SF_LAST_STEP or not isinstance(action, dict):
            return action
        me = int(_get(observation, "player", 0) or 0)
        farm = observation["farms"][me]
        positions = [tuple(farm["farmer"])] + [tuple(p) for p in farm["hands"]]
        inventories = observation["private"]["inventories"]
        commands = [list(action.get("farmer") or ["PASS"])] + [list(c) for c in (action.get("hands") or [])]
        native = _IMPL.chassis.players.get(me)
        tape = _IMPL.chassis.routes.get(native.get("route")) if native else None
        planned = {{}}
        if tape is not None:
            for t in range(step, min(len(tape), day * 24 + 24)):
                a = tape[t] or {{}}
                for u, c in enumerate([a.get("farmer") or ["PASS"]] + list(a.get("hands") or [])):
                    if c and c[0] == "FERTILIZE":
                        planned[u] = planned.get(u, 0) + 1
        carried = {{}}
        targeted = set()
        changed = False
        for unit, command in enumerate(commands[:len(positions)]):
            if not command or command[0] != "WATER":
                continue
            x, y = positions[unit]
            tile = farm["tiles"][y][x]
            if not (isinstance(tile, dict) and tile.get("kind") == "PLANT" and tile.get("crop") in _SF_CROPS):
                continue
            first, interval, max_yield = _SF_INFO[tile["crop"]]
            if tile.get("watered_today") or int(tile.get("consecutive_unwatered", 1)) != 0:
                continue
            if int(tile.get("fertilized_until_day", -1)) >= day + 1:
                continue
            planted = int(tile["planted_day"])
            today = day + 1 - planted - first          # production at the end of today?
            tomorrow = day + 2 - planted - first       # production at the end of tomorrow?
            if today >= 0 and today % interval == 0:
                continue
            if not (tomorrow >= 0 and tomorrow % interval == 0 and tomorrow // interval + 1 <= max_yield):
                continue
            if (day + 1) * 24 > 718:
                continue
            have = carried.setdefault(unit, int((inventories[unit] if unit < len(inventories) else {{}}).get("FERTILIZER", 0))
                                      - planned.get(unit, 0))
            if have <= 0 or (x, y) in targeted:
                continue
            commands[unit] = ["FERTILIZE"]
            carried[unit] = have - 1
            targeted.add((x, y))
            changed = True
            _SF_REPORT["sf_applied"] += 1
        if not changed:
            return action
        result = dict(action)
        result["farmer"], result["hands"] = commands[0], commands[1:]
        return result
    except Exception:
        _SF_REPORT["sf_errors"] += 1
        return action


straw_fert_agent.telemetry = _SF_REPORT
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", required=True)
    ap.add_argument("--out-dir", required=True)
    ap.add_argument("specs", nargs="+")
    a = ap.parse_args()
    src = Path(a.base).read_text()
    out = Path(a.out_dir); out.mkdir(parents=True, exist_ok=True)
    for spec in a.specs:
        name, body = spec.split("=", 1)
        first_day, last_step, crops = body.split(":")
        (out / f"{name}.py").write_text(src.rstrip("\n") + "\n" + WRAPPER.format(
            first_day=int(first_day), last_step=int(last_step), crops=tuple(crops.split("+"))))
        print("wrote", out / f"{name}.py")


if __name__ == "__main__":
    main()
