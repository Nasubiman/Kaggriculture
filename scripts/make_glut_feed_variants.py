#!/usr/bin/env python3
"""Append a glut-aware feeding wrapper to a base agent.

Base animal production does not depend on feeding (feeding only prevents escape
after two unfed days and realises the care bonus), so a FEED whose product
sells below ALPHA * wheat price loses money. The wrapper replaces such FEED
commands with PASS from FROM_DAY on; with KEEP_ALIVE it only skips animals fed
yesterday (consecutive_unfed == 0) so none escape.
Spec: NAME=ALPHA:FROM_DAY:KEEP_ALIVE(0/1)[:ANIMALS(+-joined):WINDOW]
The product value is the max price over the last WINDOW steps.
"""
from __future__ import annotations

import argparse
from pathlib import Path

WRAPPER = '''

# ---- glut-aware feeding (generated by scripts/make_glut_feed_variants.py): skip FEED when the
# animal's product sells below {alpha} x wheat (base production does not need feed) ----
_GF_ALPHA = {alpha}
_GF_FROM_DAY = {from_day}
_GF_KEEP_ALIVE = {keep_alive}
_GF_ANIMALS = {animals!r}
_GF_WINDOW = {window}
_GF_PRODUCT = {{"GOOSE": "EGG", "COW": "MILK", "SHEEP": "WOOL"}}
_GF_HIST = []
_GF_REPORT = {{"gf_skips": 0, "gf_errors": 0}}
_GF_BASE = [_v for _v in list(globals().values()) if callable(_v)][-1]


def glut_feed_agent(observation, configuration=None):
    action = _GF_BASE(observation, configuration)
    try:
        step = int(_get(observation, "step", 0) or 0)
        prices = observation["market"]["prices"]
        if _GF_HIST and _GF_HIST[-1][0] >= step:
            del _GF_HIST[:]
        _GF_HIST.append((step, dict(prices)))
        del _GF_HIST[:-_GF_WINDOW]
        if step // 24 < _GF_FROM_DAY or not isinstance(action, dict):
            return action
        me = int(_get(observation, "player", 0) or 0)
        farm = observation["farms"][me]
        wheat = float(prices.get("WHEAT", 0))
        units = [action.get("farmer")] + list(action.get("hands") or [])
        pos = [farm.get("farmer")] + list(farm.get("hands") or [])
        new = []
        changed = False
        for u, c in enumerate(units):
            if c and c[0] == "FEED" and u < len(pos) and pos[u]:
                x, y = int(pos[u][0]), int(pos[u][1])
                tile = farm["tiles"][y][x]
                if isinstance(tile, dict) and tile.get("animal") in _GF_ANIMALS and not tile.get("fed_today"):
                    item = _GF_PRODUCT[tile["animal"]]
                    p = max(float(h[1].get(item, 0)) for h in _GF_HIST)
                    if p < _GF_ALPHA * wheat and (not _GF_KEEP_ALIVE or int(tile.get("consecutive_unfed", 0)) == 0):
                        new.append(["PASS"]); changed = True; _GF_REPORT["gf_skips"] += 1
                        continue
            new.append(c)
        if not changed:
            return action
        out = dict(action)
        if action.get("farmer") is not None or new[0] != ["PASS"]:
            out["farmer"] = new[0]
        if action.get("hands") is not None:
            out["hands"] = new[1:]
        return out
    except Exception:
        _GF_REPORT["gf_errors"] += 1
        return action


glut_feed_agent.telemetry = _GF_REPORT
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", required=True)
    ap.add_argument("--out-dir", required=True)
    ap.add_argument("specs", nargs="+")
    a = ap.parse_args()
    src = Path(a.base).read_text()
    out = Path(a.out_dir); out.mkdir(parents=True, exist_ok=True)
    for spec in a.specs:
        name, body = spec.split("=", 1)
        parts = body.split(":")
        alpha, from_day, keep = parts[:3]
        animals = tuple(parts[3].split("+")) if len(parts) > 3 else ("GOOSE", "COW", "SHEEP")
        window = int(parts[4]) if len(parts) > 4 else 1
        (out / f"{name}.py").write_text(src.rstrip("\n") + "\n" + WRAPPER.format(
            alpha=float(alpha), from_day=int(from_day), keep_alive=bool(int(keep)), animals=animals, window=window))
        print("wrote", out / f"{name}.py")


if __name__ == "__main__":
    main()
