#!/usr/bin/env python3
"""Append a wheat-wash wrapper (seen in 21 high-rated results31-family teams on 2026-09-30).

On steps FROM..TO with step % 4 == 0 the wrapper appends BUY_PRODUCT WHEAT n at the end of the
market list and on the next step puts SELL WHEAT n in front, so the wheat is held across the
town-consumption tick. n is capped by CAP, free market slots, cash and the shed room left after
this step's orders and after what workers standing at the shed could drop next step.
Spec: NAME=FROM:TO:CAP[:HOURS(+-joined)]
"""
from __future__ import annotations

import argparse
from pathlib import Path

WRAPPER = '''

# ---- wheat wash (generated by scripts/make_wash_variants.py) ----
_WW_FROM = {lo}
_WW_TO = {hi}
_WW_CAP = {cap}
_WW_HOURS = {hours!r}
_WW_ACCESS = ((4, 4), (5, 4), (4, 5), (5, 5))
_WW_STATE = {{}}
_WW_REPORT = {{"ww_buys": 0, "ww_units": 0, "ww_sells": 0, "ww_errors": 0}}
_WW_BASE = [_v for _v in list(globals().values()) if callable(_v)][-1]


def wheat_wash_agent(observation, configuration=None):
    action = _WW_BASE(observation, configuration)
    try:
        step = int(_get(observation, "step", 0) or 0)
        me = int(_get(observation, "player", 0) or 0)
        st = _WW_STATE.setdefault(me, {{"step": -1, "pending": 0}})
        if step <= st["step"]:
            st["pending"] = 0
        st["step"] = step
        if not isinstance(action, dict):
            return action
        market = [list(o) for o in (action.get("market") or []) if o is not None]
        changed = False
        if st["pending"] > 0:
            n = st["pending"]; st["pending"] = 0
            if len(market) >= 10:
                market = market[:9]
            market.insert(0, ["SELL", "WHEAT", n])
            _WW_REPORT["ww_sells"] += 1
            changed = True
        elif _WW_FROM <= step <= _WW_TO and step % 4 == 0 and (step % 24) in _WW_HOURS and len(market) < 10:
            farm = observation["farms"][me]
            priv = observation["private"]
            shed = sum(max(0, int(v)) for v in priv["shed"].values())
            invs = priv["inventories"]
            pos = [tuple(farm["farmer"])] + [tuple(p) for p in farm["hands"]]
            near = sum(max(0, int(v)) for u, p in enumerate(pos) if tuple(p) in _WW_ACCESS and u < len(invs)
                       for v in invs[u].values())
            sells = sum(int(o[2]) for o in market if len(o) >= 3 and o[0] == "SELL")
            buys = sum(int(o[2]) for o in market if len(o) >= 3 and o[0] in ("BUY_PRODUCT", "BUY_ANIMAL"))
            room = 100 - max(0, shed - sells) - buys - near - 8
            price = float(observation["market"]["prices"].get("WHEAT", 40)) + 3.0
            cash = float(farm["money"]) - 400.0
            n = int(min(_WW_CAP, room, cash / max(1.0, price)))
            if n >= 10:
                market.append(["BUY_PRODUCT", "WHEAT", n])
                st["pending"] = n
                _WW_REPORT["ww_buys"] += 1; _WW_REPORT["ww_units"] += n
                changed = True
        if not changed:
            return action
        return dict(action, market=market)
    except Exception:
        _WW_REPORT["ww_errors"] += 1
        return action


wheat_wash_agent.telemetry = _WW_REPORT
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", required=True)
    ap.add_argument("--out-dir", required=True)
    ap.add_argument("specs", nargs="+")
    a = ap.parse_args()
    src = Path(a.base).read_text()
    out = Path(a.out_dir); out.mkdir(parents=True, exist_ok=True)
    for spec in a.specs:
        name, body = spec.split("=", 1)
        parts = body.split(":")
        lo, hi, cap = int(parts[0]), int(parts[1]), int(parts[2])
        hours = tuple(int(h) for h in parts[3].split("+")) if len(parts) > 3 else (0, 4, 8, 12, 16, 20)
        (out / f"{name}.py").write_text(src.rstrip("\n") + "\n" + WRAPPER.format(lo=lo, hi=hi, cap=cap, hours=hours))
        print("wrote", out / f"{name}.py")


if __name__ == "__main__":
    main()
